// Normal Function 1
function add(a, b) {
    return a + b;
}
// Arrow Function 1
const add = (a, b) => a + b;

// Normal Function 2
function square(number) {
    return number * number;
}
// Arrow Function 2
const square = (number) => number * number;

// Normal Function 3
function isEven(number) {
    return number % 2 === 0;
}
// Arrow Function 3
const isEven = (number) => number % 2 === 0;
